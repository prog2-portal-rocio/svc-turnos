CREATE TABLE procesos_reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    profesional_id BIGINT NOT NULL CHECK (profesional_id > 0),
    fecha DATE NOT NULL,
    hora TIME(6) NOT NULL,
    estado VARCHAR(30) NOT NULL CHECK (estado IN ('CREADO', 'HOLD_REGISTRADO')),
    hold_id TEXT,
    proceso_externo_id TEXT,
    vencimiento_hold TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL,
    actualizado_en TIMESTAMPTZ NOT NULL CHECK (actualizado_en >= creado_en),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT chk_proceso_progreso CHECK (
        (estado = 'CREADO' AND hold_id IS NULL AND proceso_externo_id IS NULL AND vencimiento_hold IS NULL)
        OR (estado = 'HOLD_REGISTRADO' AND hold_id IS NOT NULL AND LENGTH(TRIM(hold_id)) > 0
            AND proceso_externo_id IS NOT NULL AND LENGTH(TRIM(proceso_externo_id)) > 0
            AND vencimiento_hold IS NOT NULL)
    )
);
CREATE INDEX idx_procesos_reserva_usuario ON procesos_reserva(usuario_id, id);
