CREATE TABLE usuarios (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          login VARCHAR(50) NOT NULL,
                          password_hash VARCHAR(255) NOT NULL,

                          first_name VARCHAR(50) NOT NULL,
                          last_name VARCHAR(50) NOT NULL,
                          email VARCHAR(254) NOT NULL,

                          image_url VARCHAR(256),
                          lang_key VARCHAR(10) NOT NULL DEFAULT 'es',

                          activated BOOLEAN NOT NULL DEFAULT TRUE,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_usuario_login
                              CHECK (LENGTH(TRIM(login)) > 0),

                          CONSTRAINT chk_usuario_email
                              CHECK (LENGTH(TRIM(email)) > 0)
);

CREATE UNIQUE INDEX uq_usuarios_login
    ON usuarios (LOWER(login));

CREATE UNIQUE INDEX uq_usuarios_email
    ON usuarios (LOWER(email));
