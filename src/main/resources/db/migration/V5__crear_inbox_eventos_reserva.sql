CREATE TABLE eventos_reserva_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic TEXT NOT NULL,
    particion INTEGER NOT NULL CHECK (particion >= 0),
    offset_mensaje BIGINT NOT NULL CHECK (offset_mensaje >= 0),
    clave BYTEA,
    contenido BYTEA,
    payload_json TEXT,
    event_id TEXT,
    event_id_hash BYTEA,
    event_type TEXT,
    proceso_externo_id TEXT,
    hold_id TEXT,
    occurred_at TIMESTAMPTZ,
    schema_version INTEGER,
    required_field TEXT,
    mensaje TEXT,
    expires_at TIMESTAMPTZ,
    canonico BOOLEAN NOT NULL,
    estado VARCHAR(40) NOT NULL CHECK (estado IN ('RECIBIDO','SOLICITUD_REGISTRADA','PENDIENTE_CORRELACION',
        'CORRELACION_INCONSISTENTE','PENDIENTE_TIPO','INVALIDO','DUPLICADO','EVENT_ID_EN_CONFLICTO')),
    motivo VARCHAR(40),
    proceso_local_id BIGINT REFERENCES procesos_reserva(id),
    original_id BIGINT REFERENCES eventos_reserva_inbox(id),
    recibido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inbox_posicion UNIQUE(topic, particion, offset_mensaje),
    CONSTRAINT chk_inbox_canonico CHECK (NOT canonico OR
        (event_id IS NOT NULL AND event_id_hash IS NOT NULL AND OCTET_LENGTH(event_id_hash) = 32 AND LENGTH(TRIM(event_id)) > 0 AND event_type IS NOT NULL AND payload_json IS NOT NULL
         AND proceso_externo_id IS NOT NULL AND hold_id IS NOT NULL AND occurred_at IS NOT NULL
         AND schema_version = 1 AND estado NOT IN ('INVALIDO','DUPLICADO','EVENT_ID_EN_CONFLICTO'))),
    CONSTRAINT chk_inbox_solicitud CHECK (estado <> 'SOLICITUD_REGISTRADA' OR
        (proceso_local_id IS NOT NULL AND required_field = 'PHONE_NUMBER' AND mensaje IS NOT NULL AND expires_at IS NOT NULL))
);
-- Índice de tamaño fijo: el contrato no limita la longitud de los identificadores opacos.
-- Los conflictos se resuelven consultando el eventId completo y comparando el contenido conservado.
CREATE UNIQUE INDEX uq_inbox_event_id ON eventos_reserva_inbox(event_id_hash) WHERE canonico;
CREATE INDEX idx_inbox_pendientes ON eventos_reserva_inbox(estado, id);
CREATE INDEX idx_proceso_reserva_externo ON procesos_reserva USING hash(proceso_externo_id);
